#requires -Version 7.0
<#
.SYNOPSIS
    Clones folo at a pinned commit into a local cache and generates the
    iteration-3 full-workspace task YAML enumerating every file as an
    `inputs.files` entry.

.DESCRIPTION
    Wired as the `before_run` hook for the ss-cargo-deps-tidy eval. Runs
    every `waza run` but is fully idempotent — re-clone is skipped when
    the cache HEAD already matches the pinned SHA.

    Outputs:
      - evals/ss-cargo-deps-tidy/fixtures/.eval-cache/folo-3e1f241/
        (gitignored full git checkout, .git kept for diagnostic tooling)
      - evals/ss-cargo-deps-tidy/tasks/folo/folo-3e1f241-full.yaml
        (gitignored generated task spec)

    Designed to be invoked from the repo root (CWD = c:\Source\ss-ai).
#>

[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$pinnedSha    = '3e1f241ddfb6de7ab0ecca1a54ca923807135d83'
$shortSha     = '3e1f241'
$repoUrl      = 'https://github.com/folo-rs/folo.git'

$evalDir      = 'evals/ss-cargo-deps-tidy'
$cacheDir     = "$evalDir/fixtures/.eval-cache/folo-$shortSha"
$taskFile     = "$evalDir/tasks/folo/folo-$shortSha-full.yaml"

# 1. Ensure cache exists and is at the pinned SHA.
$needClone = $true
if (Test-Path (Join-Path $cacheDir '.git')) {
    $current = (& git -C $cacheDir rev-parse HEAD 2>$null).Trim()
    if ($LASTEXITCODE -eq 0 -and $current -eq $pinnedSha) {
        Write-Host "[prepare-folo] cache at $shortSha already up to date"
        $needClone = $false
    } else {
        Write-Host "[prepare-folo] cache HEAD '$current' != '$pinnedSha', refetching"
    }
}

if ($needClone) {
    if (Test-Path $cacheDir) {
        # Fetch + checkout into existing clone for speed.
        & git -C $cacheDir fetch --depth 1 origin $pinnedSha 2>&1 | Out-Host
        if ($LASTEXITCODE -ne 0) { throw "git fetch failed" }
        & git -C $cacheDir checkout --detach $pinnedSha 2>&1 | Out-Host
        if ($LASTEXITCODE -ne 0) { throw "git checkout failed" }
    } else {
        Write-Host "[prepare-folo] cloning $repoUrl into $cacheDir"
        New-Item -ItemType Directory -Force -Path (Split-Path $cacheDir -Parent) | Out-Null
        & git clone --filter=blob:none $repoUrl $cacheDir 2>&1 | Out-Host
        if ($LASTEXITCODE -ne 0) { throw "git clone failed" }
        & git -C $cacheDir checkout --detach $pinnedSha 2>&1 | Out-Host
        if ($LASTEXITCODE -ne 0) { throw "git checkout failed (commit not in default fetch?)" }
    }

    $verify = (& git -C $cacheDir rev-parse HEAD).Trim()
    if ($verify -ne $pinnedSha) {
        throw "cache HEAD '$verify' does not match pinned '$pinnedSha' after checkout"
    }
}

# 2. Enumerate every file under cache (excluding .git, target).
$cacheFull = (Resolve-Path $cacheDir).Path
$files = Get-ChildItem -Path $cacheFull -Recurse -File -Force `
    | Where-Object { $_.FullName -notmatch '[\\/](\.git|target)[\\/]' } `
    | ForEach-Object { $_.FullName.Substring($cacheFull.Length + 1) -replace '\\', '/' } `
    | Sort-Object

if (-not $files) { throw "no files found in cache $cacheDir" }
Write-Host "[prepare-folo] enumerated $($files.Count) files"

# 3. Generate the task YAML. Inline graders to avoid leaking strict
#    grader config onto the manifest-only iteration-1 task.
$expectedRel = 'fixtures/folo-3e1f241-expected'
$snapshots = Get-ChildItem -Path (Join-Path $evalDir $expectedRel) -Recurse -File -Filter 'Cargo.toml' `
    | ForEach-Object {
        $rel = $_.FullName.Substring((Resolve-Path (Join-Path $evalDir $expectedRel)).Path.Length + 1) -replace '\\', '/'
        # Snapshot is resolved against the diff grader's context_dir (set
        # to "$evalDir/fixtures" below), so prefix with the expected-tree
        # name only — NOT with `fixtures/`, which would double up.
        [PSCustomObject]@{ Path = $rel; Snapshot = "folo-3e1f241-expected/$rel" }
    }

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('# AUTOGENERATED by scripts/Generate-FoloFullTask.ps1 — do not edit.')
[void]$sb.AppendLine('# Regenerated by the `before_run` hook on every `waza run`.')
[void]$sb.AppendLine("id: folo-$shortSha-full")
[void]$sb.AppendLine("name: Folo @ $shortSha - full workspace tidy")
[void]$sb.AppendLine('description: >')
[void]$sb.AppendLine("  Iteration-3 full-workspace eval extracted from folo-rs/folo at commit")
[void]$sb.AppendLine("  $pinnedSha. The agent receives the complete source tree (sources, lockfile,")
[void]$sb.AppendLine('  AGENTS.md, justfile) and is expected to apply ss-cargo-deps-tidy with')
[void]$sb.AppendLine('  `cargo` verification enabled. Only Cargo.toml files and Cargo.lock may be')
[void]$sb.AppendLine('  modified; source files must be byte-identical to upstream.')
[void]$sb.AppendLine('tags:')
[void]$sb.AppendLine('  - folo')
[void]$sb.AppendLine('  - real-world')
[void]$sb.AppendLine('  - full-workspace')
[void]$sb.AppendLine('  - devenv')
[void]$sb.AppendLine('timeout_seconds: 3600')
[void]$sb.AppendLine("context_dir: $cacheDir")
[void]$sb.AppendLine('inputs:')
[void]$sb.AppendLine('  prompt: >')
[void]$sb.AppendLine('    Tidy Cargo dependencies across this Rust workspace. The full skill flow')
[void]$sb.AppendLine('    applies, including stage 5 `cargo check` verification and stage 7')
[void]$sb.AppendLine('    `cargo generate-lockfile` minimum-version verification.')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('    Important constraints:')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('    - Modify only Cargo.toml files and Cargo.lock. Do not edit any source')
[void]$sb.AppendLine('      files (.rs, .md, .json, etc.) — they must remain byte-identical to the')
[void]$sb.AppendLine('      upstream commit.')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('    - WORKAROUND for an upstream waza/copilot-cli bug (microsoft/waza;')
[void]$sb.AppendLine('      copilot-sdk#947): do not invoke the `task` tool to spawn sub-agents.')
[void]$sb.AppendLine('      Sub-agent tool calls hang indefinitely on copilot-cli 1.0.2 (bundled in')
[void]$sb.AppendLine('      waza 0.31.0); the fix shipped in copilot-cli 1.0.49. Read and edit files')
[void]$sb.AppendLine('      directly with `view` / `str_replace` / `create`. Remove this constraint')
[void]$sb.AppendLine('      once waza ships a release with copilot-cli >= 1.0.49.')
[void]$sb.AppendLine('  files:')
foreach ($f in $files) { [void]$sb.AppendLine("    - path: $f") }
[void]$sb.AppendLine('expected:')
[void]$sb.AppendLine('  outcomes:')
[void]$sb.AppendLine('    - type: task_completed')
[void]$sb.AppendLine('graders:')
[void]$sb.AppendLine('  - name: cargo-manifests-match-expected')
[void]$sb.AppendLine('    type: diff')
[void]$sb.AppendLine('    config:')
[void]$sb.AppendLine("      context_dir: $evalDir/fixtures")
[void]$sb.AppendLine('      expected_files:')
foreach ($s in $snapshots) {
    [void]$sb.AppendLine("        - { path: $($s.Path), snapshot: $($s.Snapshot) }")
}
[void]$sb.AppendLine('  - name: source-files-untouched')
[void]$sb.AppendLine('    type: program')
[void]$sb.AppendLine('    config:')
[void]$sb.AppendLine('      command: pwsh')
[void]$sb.AppendLine('      args:')
[void]$sb.AppendLine('        - -NoProfile')
[void]$sb.AppendLine('        - -File')
[void]$sb.AppendLine("        - $evalDir/scripts/Test-SourceUntouched.ps1")
[void]$sb.AppendLine("        - -CacheDir")
[void]$sb.AppendLine("        - $cacheDir")
[void]$sb.AppendLine('      timeout: 120')
[void]$sb.AppendLine('  - name: lockfile-modified-or-created')
[void]$sb.AppendLine('    type: program')
[void]$sb.AppendLine('    config:')
[void]$sb.AppendLine('      command: pwsh')
[void]$sb.AppendLine('      args:')
[void]$sb.AppendLine('        - -NoProfile')
[void]$sb.AppendLine('        - -File')
[void]$sb.AppendLine("        - $evalDir/scripts/Test-LockfileModified.ps1")
[void]$sb.AppendLine("        - -CacheDir")
[void]$sb.AppendLine("        - $cacheDir")
[void]$sb.AppendLine('      timeout: 30')
[void]$sb.AppendLine('  - name: stage-7-min-version-bumps')
[void]$sb.AppendLine('    type: file')
[void]$sb.AppendLine('    config:')
[void]$sb.AppendLine('      content_patterns:')
[void]$sb.AppendLine('        - path: Cargo.toml')
[void]$sb.AppendLine('          must_match:')
[void]$sb.AppendLine("            - 'libc\s*=\s*\{\s*version\s*=\s*\""0\.2\.[1-9]\d*\""'")
[void]$sb.AppendLine("            - 'proc-macro2\s*=\s*\{\s*version\s*=\s*\""1\.0\.[1-9]\d*\""'")
[void]$sb.AppendLine("            - 'tracing\s*=\s*\{\s*version\s*=\s*\""0\.1\.[1-9]\d*\""'")
[void]$sb.AppendLine("            - 'syn\s*=\s*\{\s*version\s*=\s*\""2\.0\.[1-9]\d*\""'")
[void]$sb.AppendLine("            - 'fake_headers\s*=\s*\{\s*version\s*=\s*\""0\.0\.[1-9]\d*\""'")

New-Item -ItemType Directory -Force -Path (Split-Path $taskFile -Parent) | Out-Null
Set-Content -Path $taskFile -Value $sb.ToString() -Encoding utf8 -NoNewline
Write-Host "[prepare-folo] wrote $taskFile ($($files.Count) files, $($snapshots.Count) snapshots)"
